package org.openrewrite;

import com.fasterxml.jackson.annotation.JsonIgnore;
import org.jspecify.annotations.Nullable;
import org.openrewrite.config.RecipeDescriptor;

import java.util.ArrayList;
import java.util.Collection;
import java.util.List;
import java.util.UUID;

import static java.util.Collections.emptyList;

/**
 * A recipe that may first scan a repository and study it in one pass over the
 * repository's source files before, in another pass, it decides how to transform
 * the code.
 * <br/>
 * New source file generation is part of this type as well, since in almost every case
 * we check that a file doesn't yet exist (and perhaps other conditions) before deciding
 * to generate a file.
 *
 * @param <T> The type of the accumulator where scanning data is held until the transformation phase. It stays in
 *            memory until the cycle ends, so it should hold values such as coordinates, paths and ids, not trees or
 *            other {@link Heavyweight} objects.
 */
@SuppressWarnings("ALL")
public abstract class ScanningRecipe<T> extends Recipe {
    private String recipeAccMessage = "org.openrewrite.recipe.acc." + UUID.randomUUID();

    String getRecipeAccMessage() {
        return recipeAccMessage;
    }

    /**
     * @return The initial value of the accumulator before any source files have been iterated over.
     */
    public abstract T getInitialValue(ExecutionContext ctx);

    /**
     * A visitor that is called for each source file in the repository in an initial pass.
     * Scanning data should be accumulated to <code>acc</code>. The first source file to visit
     * will receive an <code>acc</code> value that is supplied by {@link #getInitialValue(ExecutionContext)}.
     * <br/>
     * Any changes that the scanning visitor makes to the source file will be discarded.
     *
     * @param acc The accumulated scanning data.
     * @return A visitor that is called to collect scanning data on each source file.
     */
    public abstract TreeVisitor<?, ExecutionContext> getScanner(T acc);

    /**
     * Generate new source files to add to the repository using information collected from scanning.
     *
     * @param acc                  The accumulated scanning data.
     * @param generatedInThisCycle Files generated by other recipes in this cycle.
     * @return A list of new source files.
     */
    public Collection<? extends SourceFile> generate(T acc, Collection<SourceFile> generatedInThisCycle, ExecutionContext ctx) {
        return generate(acc, ctx);
    }

    /**
     * Generate new source files to add to the repository using information collected from scanning.
     *
     * @param acc The accumulated scanning data.
     * @return A list of new source files.
     */
    public Collection<? extends SourceFile> generate(T acc, ExecutionContext ctx) {
        return emptyList();
    }

    /**
     * A visitor that is called in a second pass to perform transformation on each source file.
     * To delete a source file, return <code>null</code> from the {@link TreeVisitor#visit(Tree, Object)}
     * method.
     *
     * @param acc The accumulated scanning data.
     * @return A visitor that is called to perform transformation on each source file.
     */
    public TreeVisitor<?, ExecutionContext> getVisitor(T acc) {
        return TreeVisitor.noop();
    }

    /**
     * Conditions that a source file must meet before this recipe's {@link #getVisitor(Object) editing visitor}
     * and the editing visitors of every recipe in its {@link #getRecipeList() recipe list}, recursively, may
     * change it. This is the programmatic equivalent of the {@code preconditions} of a declarative recipe:
     * <pre>{@code
     * @Override
     * public List<Recipe> getEditPreconditions() {
     *     return singletonList(new RepositoryContainsFile("pom.xml"));
     * }
     * }</pre>
     * A source file matches when every listed condition marks it as found. A condition with a recipe list also
     * matches when any recipe in that list does. The conditions are evaluated once per source file in each cycle,
     * immediately before this recipe edits it and with the edits of the recipes that ran before it, and that result
     * then applies to the whole recipe list.
     * <p>
     * Scanning and generation are not affected: this recipe and its recipe list still scan every source file and
     * generate new ones, which are then edited only if they match. A {@link ScanningRecipe} condition scans every
     * source file into an accumulator of its own before its editing visitor decides. Conditions never generate
     * source files, and the changes they make while deciding are discarded.
     *
     * @return The conditions, which by default are none.
     */
    @Incubating(since = "8.111.0")
    @JsonIgnore
    public List<Recipe> getEditPreconditions() {
        return emptyList();
    }

    public T getAccumulator(Cursor cursor, ExecutionContext ctx) {
        return cursor.getRoot().computeMessageIfAbsent(getRecipeAccMessage(), m -> getInitialValue(ctx));
    }

    @Override
    public final TreeVisitor<?, ExecutionContext> getVisitor() {
        return new TreeVisitor<Tree, ExecutionContext>() {

            @Nullable
            private TreeVisitor<?, ExecutionContext> delegate;

            private TreeVisitor<?, ExecutionContext> delegate(ExecutionContext ctx) {
                if (delegate == null) {
                    delegate = getVisitor(getAccumulator(getCursor(), ctx));
                }
                return delegate;
            }

            @Override
            public boolean isAcceptable(SourceFile sourceFile, ExecutionContext ctx) {
                return delegate(ctx).isAcceptable(sourceFile, ctx);
            }

            @Override
            public @Nullable Tree visit(@Nullable Tree tree, ExecutionContext ctx, Cursor parent) {
                return delegate(ctx).visit(tree, ctx, parent);
            }

            @Override
            public @Nullable Tree visit(@Nullable Tree tree, ExecutionContext ctx) {
                return delegate(ctx).visit(tree, ctx);
            }
        };
    }

    @Override
    public Collection<Validated<Object>> validateAll(ExecutionContext ctx, Collection<Validated<Object>> acc) {
        super.validateAll(ctx, acc);
        for (Recipe editPrecondition : getEditPreconditions()) {
            editPrecondition.validateAll(ctx, acc);
        }
        return acc;
    }

    @Override
    protected RecipeDescriptor createRecipeDescriptor() {
        RecipeDescriptor descriptor = super.createRecipeDescriptor();
        List<Recipe> editPreconditions = getEditPreconditions();
        if (editPreconditions.isEmpty()) {
            return descriptor;
        }
        List<RecipeDescriptor> preconditions = new ArrayList<>(descriptor.getPreconditions());
        for (Recipe editPrecondition : editPreconditions) {
            RecipeDescriptor preconditionDescriptor = editPrecondition.getDescriptor();
            if (!preconditions.contains(preconditionDescriptor)) {
                preconditions.add(preconditionDescriptor);
            }
        }
        return descriptor.withPreconditions(preconditions);
    }

    @Override
    public ScanningRecipe<T> clone() {
        ScanningRecipe<T> cloned = (ScanningRecipe<T>) super.clone();
        cloned.recipeAccMessage = "org.openrewrite.recipe.acc." + UUID.randomUUID();
        return cloned;
    }
}
