import static org.openrewrite.javascript.internal.lock.V8RegExp.DOT;
import static org.openrewrite.javascript.internal.lock.npm.Js.truthy;

/**
 * Port of @npmcli/arborist lib/yarn-lock.js (npm 11.17.0): the yarn.lock npm reads beside its own lock.
 */
public final class YarnLock {

    private static final String NOT_SPACE = "[^" + Js.WHITESPACE_CLASS + "]";

    private static final Pattern LINE = Pattern.compile("([^\\r\\n]*)\\r?\\n");
    private static final Pattern ENTRY_START = Pattern.compile(NOT_SPACE + DOT + "*:");
    private static final Pattern SUBKEY = Pattern.compile(" {2}" + NOT_SPACE + "+:");
    private static final Pattern SUBVAL = Pattern.compile(" {4}" + NOT_SPACE + "+ " + DOT + "+");
    private static final Pattern METADATA = Pattern.compile(" {2}" + NOT_SPACE + "+ " + DOT + "+");
    private static final Pattern LEGACY_SHASUM = Pattern.compile("#" + DOT + "*");
    private static final Pattern SPEC_DELIMITER = Pattern.compile(", *");
    private static final Pattern SPACE = Pattern.compile(" ");
    private static final Pattern QUOTED = Pattern.compile("\"" + DOT + "*\"");
    private static final Pattern CLOSING_QUOTE = Pattern.compile("[^\\\\](\\\\\\\\)*\"\\z");
    private static final Pattern NEEDS_QUOTES = Pattern.compile("[:" + Js.WHITESPACE_CLASS + "\\\\\",\\[\\]]");

    private static final String PREFIX =
            "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n" +
            "# yarn lockfile v1\n\n\n";

    private static final Map<String, Integer> ENTRY_PRIORITIES = new HashMap<>();

    static {
        String[] keys = {"name", "version", "uid", "resolved", "integrity", "registry", "dependencies"};
        for (int i = 0; i < keys.length; i++) {
            ENTRY_PRIORITIES.put(keys[i], i + 1);
        }
    }

    /**
     * The error for a line that is not yarn.lock syntax.
     */
    @Getter
    public static final class InvalidYarnLock extends IllegalArgumentException {
        private final int position;
        private final String content;
        private final int line;

        InvalidYarnLock(int position, String content, int line) {
            super("invalid or corrupted yarn.lock file");
            this.position = position;
            this.content = content;
            this.line = line;
        }
    }

    @Getter
    private @Nullable Map<String, Entry> entries;

    private @Nullable Entry current;
    private @Nullable String subkey;

    private void endCurrent() {
        current = null;
        subkey = null;
    }

    @SuppressWarnings("unchecked")
    public YarnLock parse(String data) {
        Map<String, Entry> entries = new LinkedHashMap<>();
        this.entries = entries;
        current = null;
        int lineNum = 0;
        if (!data.endsWith("\n")) {
            data += "\n";
        }
        Matcher match = LINE.matcher(data);
        while (match.find()) {
            String line = match.group(1);
            lineNum++;
            if (line.startsWith("#")) {
                continue;
            }
            if (line.isEmpty()) {
                endCurrent();
                continue;
            }
            if (ENTRY_START.matcher(line).matches()) {
                endCurrent();
                List<String> specs = splitQuoted(line.substring(0, line.length() - 1), SPEC_DELIMITER);
                Entry entry = new Entry(specs);
                current = entry;
                for (String spec : specs) {
                    entries.put(spec, entry);
                }
                continue;
            }
            if (SUBKEY.matcher(line).matches()) {
                if (current == null) {
                    throw new JsError(JsError.TYPE_ERROR, "Cannot set properties of null");
                }
                subkey = line.substring(2, line.length() - 1);
                current.fields.put(subkey, new LinkedHashMap<String, Object>());
                continue;
            }
            if (SUBVAL.matcher(line).matches() && current != null && subkey != null && truthy(current.get(subkey))) {
                List<String> subval = splitQuoted(Js.trimStart(line), SPACE);
                if (subval.size() == 2) {
                    Object object = current.get(subkey);
                    if (!(object instanceof Map)) {
                        throw new JsError(JsError.TYPE_ERROR, "Cannot create property '" + subval.get(0) + "' on " +
                                object);
                    }
                    ((Map<String, Object>) object).put(subval.get(0), subval.get(1));
                    continue;
                }
            }
            if (METADATA.matcher(line).matches() && current != null) {
                List<String> metadata = splitQuoted(Js.trimStart(line), SPACE);
                if (metadata.size() == 2) {
                    String value = metadata.get(1);
                    if ("resolved".equals(metadata.get(0))) {
                        value = LEGACY_SHASUM.matcher(value).replaceFirst("");
                    }
                    current.fields.put(metadata.get(0), value);
                    continue;
                }
            }

            throw new InvalidYarnLock(match.start(), match.group(), lineNum);
        }
        endCurrent();
        return this;
    }

    List<String> splitQuoted(String str, Pattern delim) {
        String[] split = delim.split(str, -1);
        List<String> out = new ArrayList<>();
        for (int i = 0; i < split.length; i++) {
            String chunk = split[i];
            if (QUOTED.matcher(chunk).matches()) {
                String trimmed = Js.trim(chunk);
                out.add(trimmed.substring(1, trimmed.length() - 1));
            } else if (chunk.startsWith("\"")) {
                StringBuilder collect = new StringBuilder(Js.trimStart(chunk).substring(1));
                while (++i < split.length) {
                    String n = split[i];
                    if (CLOSING_QUOTE.matcher(n).find()) {
                        String trimmed = Js.trimEnd(n);
                        collect.append(trimmed, 0, trimmed.length() - 1);
                        break;
                    } else {
                        collect.append(n);
                    }
                }
                out.add(collect.toString());
            } else {
                out.add(Js.trim(chunk));
            }
        }
        return out;
    }

    @Override
    public String toString() {
        List<String> printed = new ArrayList<>();
        for (Entry entry : new LinkedHashSet<>(Objects.requireNonNull(entries).values())) {
            printed.add(entry.toString());
        }
        printed.sort((a, b) -> LocaleCompare.en(a.replace("\"", ""), b.replace("\"", "")));
        return PREFIX + String.join("\n\n", printed) + "\n";
    }

    public YarnLock fromTree(Node tree) {
        entries = new LinkedHashMap<>();
        Deque<Node> queue = new ArrayDeque<>();
        Set<Node> seen = new HashSet<>();
        queue.add(tree);
        while (!queue.isEmpty()) {
            Node node = queue.poll();
            if (!seen.add(node)) {
                continue;
            }
            addEntryFromNode(node);
            List<Node> kids = new ArrayList<>(node.getChildren().values());
            kids.addAll(node.getFsChildren());
            kids.sort((a, b) -> a.getDepth() != b.getDepth() ? Integer.compare(a.getDepth(), b.getDepth()) :
                    LocaleCompare.en(String.valueOf(a.getName()), String.valueOf(b.getName())));
            queue.addAll(kids);
        }
        return this;
    }

    void addEntryFromNode(Node node) {
        Map<String, Entry> entries = Objects.requireNonNull(this.entries);
        List<String> specs = new ArrayList<>();
        for (Edge e : node.getEdgesIn()) {
            specs.add(node.getName() + "@" + e.getSpec());
        }
        specs.sort(LocaleCompare::en);

        Map<String, Object> n = entryDataFromNode(node);
        Entry priorEntry = null;
        List<String> newSpecs = new ArrayList<>();
        for (String s : specs) {
            Entry prev = entries.get(s);
            if (prev == null) {
                if (priorEntry != null) {
                    priorEntry.addSpec(s);
                } else {
                    newSpecs.add(s);
                }
                continue;
            }

            if (!match(prev, n)) {
                continue;
            }

            if (priorEntry == null) {
                priorEntry = prev;
                for (String newSpec : newSpecs) {
                    priorEntry.addSpec(newSpec);
                    entries.put(newSpec, priorEntry);
                }
                newSpecs.clear();
                continue;
            }

            priorEntry.addSpec(s);
            entries.put(s, priorEntry);
        }

        if (priorEntry == null) {
            Entry entry = new Entry(newSpecs);
            entry.fields.putAll(n);
            for (String s : newSpecs) {
                entries.put(s, entry);
            }
        } else {
            priorEntry.fields.putAll(n);
        }
    }

    private static boolean match(Entry p, Map<String, Object> n) {
        for (String field : new String[]{"integrity", "resolved", "version"}) {
            if (truthy(p.get(field)) && truthy(n.get(field))) {
                return Objects.equals(p.get(field), n.get(field));
            }
        }
        return true;
    }

    Map<String, Object> entryDataFromNode(Node node) {
        Map<String, Object> n = new LinkedHashMap<>();
        Object dependencies = node.getPackage().get("dependencies");
        if (truthy(dependencies)) {
            n.put("dependencies", dependencies);
        }
        Object optionalDependencies = node.getPackage().get("optionalDependencies");
        if (truthy(optionalDependencies)) {
            n.put("optionalDependencies", optionalDependencies);
        }
        if (truthy(node.getVersion())) {
            n.put("version", node.getVersion());
        }
        if (truthy(node.getResolved())) {
            String from = node.isLink() ? PosixPath.dirname(node.getPath()) : node.getPath();
            n.put("resolved",
                    ConsistentResolve.consistentResolve(node.getResolved(), from, node.getRoot().getPath(), true));
        }
        if (truthy(node.getIntegrity())) {
            n.put("integrity", node.getIntegrity());
        }
        return n;
    }

    private static String quoteIfNeeded(@Nullable Object val) {
        if (val instanceof Boolean || val instanceof Number) {
            return String.valueOf(val);
        }
        if (!(val instanceof String)) {
            throw new JsError(JsError.TYPE_ERROR, val == null ? "Cannot read properties of undefined (reading " +
                                                                "'startsWith')" : "val.startsWith is not a function");
        }
        String s = (String) val;
        char first = s.isEmpty() ? 0 : s.charAt(0);
        boolean startsWithLetter = first >= 'a' && first <= 'z' || first >= 'A' && first <= 'Z';
        if (s.startsWith("true") || s.startsWith("false") || NEEDS_QUOTES.matcher(s).find() || !startsWithLetter) {
            return Js.quote(s);
        }
        return s;
    }

    private static String sortKV(Map<String, Object> obj) {
        List<String> keys = new ArrayList<>(obj.keySet());
        keys.sort(LocaleCompare::en);
        List<String> lines = new ArrayList<>();
        for (String k : keys) {
            lines.add("    " + quoteIfNeeded(k) + " " + quoteIfNeeded(obj.get(k)));
        }
        return String.join("\n", lines);
    }

    private static int priorityThenLocaleCompare(String a, String b) {
        Integer pa = ENTRY_PRIORITIES.get(a);
        Integer pb = ENTRY_PRIORITIES.get(b);
        if (pa == null && pb == null) {
            return LocaleCompare.en(a, b);
        }
        return (pa != null ? pa : 100) > (pb != null ? pb : 100) ? 1 : -1;
    }

    /**
     * Arborist's {@code YarnLockEntry}: the specs that share one resolution, and its fields.
     */
    public static final class Entry {
        private final Set<String> specs;
        private final Map<String, @Nullable Object> fields = new LinkedHashMap<>();

        Entry(Collection<String> specs) {
            this.specs = new LinkedHashSet<>(specs);
            String[] written = {"resolved", "version", "integrity", "dependencies", "optionalDependencies"};
            for (String field : written) {
                fields.put(field, null);
            }
        }

        public @Nullable Object get(String field) {
            return fields.get(field);
        }

        void set(String field, @Nullable Object value) {
            fields.put(field, value);
        }

        void addSpec(String spec) {
            specs.add(spec);
        }

        @Override
        public String toString() {
            List<String> sortedSpecs = new ArrayList<>(specs);
            sortedSpecs.sort(LocaleCompare::en);
            List<String> quotedSpecs = new ArrayList<>();
            for (String spec : sortedSpecs) {
                quotedSpecs.add(quoteIfNeeded(spec));
            }
            StringBuilder sb = new StringBuilder(String.join(", ", quotedSpecs)).append(":\n");

            List<String> props = new ArrayList<>();
            for (Map.Entry<String, @Nullable Object> field : fields.entrySet()) {
                if (field.getValue() != null) {
                    props.add(field.getKey());
                }
            }
            props.sort(YarnLock::priorityThenLocaleCompare);
            for (String prop : props) {
                Object val = fields.get(prop);
                Map<String, Object> object = asObject(val);
                if (object == null) {
                    boolean quoted = !"integrity".equals(prop) && val instanceof String;
                    sb.append("  ").append(prop).append(' ')
                            .append(quoted ? Js.quote((String) val) : String.valueOf(val)).append('\n');
                } else if (!object.isEmpty()) {
                    sb.append("  ").append(prop).append(":\n").append(sortKV(object)).append('\n');
                }
            }
            return Js.trim(sb.toString());
        }

        @SuppressWarnings("unchecked")
        private static @Nullable Map<String, Object> asObject(@Nullable Object val) {
            if (val instanceof Map) {
                return (Map<String, Object>) val;
            }
            if (val instanceof List) {
                Map<String, Object> byIndex = new LinkedHashMap<>();
                for (Object element : (List<?>) val) {
                    byIndex.put(String.valueOf(byIndex.size()), element);
                }
                return byIndex;
            }
            return null;
        }
    }
}
