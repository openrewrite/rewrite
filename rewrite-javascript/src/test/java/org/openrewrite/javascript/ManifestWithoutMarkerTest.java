package org.openrewrite.javascript;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.MethodSource;
import org.openrewrite.Recipe;
import org.openrewrite.javascript.internal.NodeDependencyEdits;
import org.openrewrite.javascript.table.NodeDependencyEditsDeclined;
import org.openrewrite.javascript.table.NodeLockRegenerationFailures;
import org.openrewrite.test.RewriteTest;

import java.util.stream.Stream;

import static org.assertj.core.api.Assertions.assertThat;
import static org.openrewrite.json.Assertions.json;
import static org.openrewrite.test.SourceSpecs.text;

/**
 * A host whose install fails parses package.json without its {@code NodeResolutionResult} marker. A recipe that
 * would edit such a manifest leaves it and its lock as they are and says so with one row.
 */
class ManifestWithoutMarkerTest implements RewriteTest {

    private static final String MANIFEST = "{\n" +
                                           "  \"name\": \"app\",\n" +
                                           "  \"version\": \"1.0.0\",\n" +
                                           "  \"devDependencies\": {\n" +
                                           "    \"npm-run-all\": \"^4.1.5\",\n" +
                                           "    \"prettier\": \"^2.8.8\"\n" +
                                           "  }\n" +
                                           "}\n";

    private static final String YARN_LOCK = "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n" +
                                            "# yarn lockfile v1\n\n\n" +
                                            "cross-spawn@^6.0.5:\n" +
                                            "  version \"6.0.5\"\n";

    static Stream<Recipe> recipesThatWouldEdit() {
        return Stream.of(
          new UpgradeDependencyVersion("prettier", null, "^3.6.2"),
          new UpgradeTransitiveDependencyVersion("cross-spawn", "^7.0.6", null),
          new AddDependency("is-number", "^7.0.0", null),
          new RemoveDependency("prettier", null),
          new ChangeDependency("npm-run-all", "npm-run-all2", "^9.0.3", null));
    }

    @ParameterizedTest
    @MethodSource("recipesThatWouldEdit")
    void aRecipeThatWouldEditAManifestWithoutItsMarkerDeclinesIt(Recipe recipe) {
        rewriteRun(
          spec -> spec.recipe(recipe)
            .dataTable(NodeDependencyEditsDeclined.Row.class, rows -> assertThat(rows).singleElement()
              .satisfies(row -> {
                  assertThat(row.getSourcePath()).isEqualTo("package.json");
                  assertThat(row.getReason()).isEqualTo(NodeDependencyEdits.UNMARKED);
              }))
            .afterRecipe(run -> assertThat(run.getDataTableRows(NodeLockRegenerationFailures.class)).isEmpty()),
          json(MANIFEST, spec -> spec.path("package.json")),
          text(YARN_LOCK, spec -> spec.path("yarn.lock"))
        );
    }

    @Test
    void aRecipeThatWouldNotEditItSaysNothing() {
        rewriteRun(
          spec -> spec.recipe(new UpgradeDependencyVersion("typescript", null, "^5.9.3"))
            .afterRecipe(run -> {
                assertThat(run.getDataTableRows(NodeDependencyEditsDeclined.class)).isEmpty();
                assertThat(run.getDataTableRows(NodeLockRegenerationFailures.class)).isEmpty();
            }),
          json(MANIFEST, spec -> spec.path("package.json")),
          text(YARN_LOCK, spec -> spec.path("yarn.lock"))
        );
    }

}
