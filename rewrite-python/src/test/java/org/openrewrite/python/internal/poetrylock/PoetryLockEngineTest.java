package org.openrewrite.python.internal.poetrylock;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.provider.CsvSource;
import org.junit.jupiter.params.ParameterizedTest;
import org.openrewrite.ExecutionContext;
import org.openrewrite.HttpSenderExecutionContextView;
import org.openrewrite.InMemoryExecutionContext;
import org.openrewrite.ipc.http.HttpSender;
import org.openrewrite.python.PythonExecutionContextView;
import org.openrewrite.python.PythonPackageIndex;
import org.openrewrite.python.internal.LockFileRegeneration.Reason;
import org.openrewrite.python.internal.LockFileRegeneration.Result;

import java.io.ByteArrayInputStream;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

import static org.assertj.core.api.Assertions.assertThat;
import static org.openrewrite.python.internal.poetrylock.PoetryLockFixtures.resource;

/**
 * Golden scenarios replay Poetry 2.4.1 runs against pypi.org (see the fixture README); the
 * recorded index/metadata responses under {@code /lock/poetry/http/} keep the tests offline.
 */
class PoetryLockEngineTest {

    RoutedHttp http;
    ExecutionContext ctx;

    @BeforeEach
    void setUp() {
        http = new RoutedHttp();
        ctx = new InMemoryExecutionContext(Throwable::printStackTrace);
        HttpSenderExecutionContextView.view(ctx).setHttpSender(http);
        PythonExecutionContextView.view(ctx).setPackageIndexes(List.of(
                new PythonPackageIndex("pypi", "https://pypi.org/simple", true, null, null, false)));
    }

    private void stubPypiSix() {
        http.route("https://pypi.org/simple/six/", resource("http/six-simple-json"));
        http.route("https://files.pythonhosted.org/packages/b7/ce/149a00dd41f10bc29e5921b496af8b574d8413afcd5e30dfa0ed46c2cc5e/six-1.17.0-py2.py3-none-any.whl.metadata",
                resource("http/six-1.17.0-py2.py3-none-any.whl.metadata"));
    }

    @Test
    void pinBumpMatchesRealPoetryByteForByte() {
        stubPypiSix();
        Result result = PoetryLockEngine.regenerate(
                resource("i-upgrade/pyproject.toml.after"),
                resource("i-upgrade/poetry.lock.before"),
                ctx);
        assertThat(result.getErrorMessage()).isNull();
        assertThat(result.getLockFileContent()).isEqualTo(resource("i-upgrade/poetry.lock.after"));
    }

    @Test
    void noOpRelockIsByteIdenticalWithoutNetwork() {
        Result result = PoetryLockEngine.regenerate(
                resource("i-upgrade/pyproject.toml.after"),
                resource("i-upgrade/poetry.lock.after"),
                ctx);
        assertThat(result.getErrorMessage()).isNull();
        assertThat(result.getLockFileContent()).isEqualTo(resource("i-upgrade/poetry.lock.after"));
        assertThat(http.requests).isEmpty();
    }

    @Test
    void addingDependencyDefersToResolution() {
        String pyproject = resource("a-minimal/pyproject.toml")
                .replace("six = \"1.16.0\"", "six = \"1.16.0\"\nattrs = \"25.1.0\"");
        Result result = PoetryLockEngine.regenerate(pyproject, resource("a-minimal/poetry.lock"), ctx);
        assertThat(result.isSuccess()).isFalse();
        assertThat(result.getFailure().getReason()).isEqualTo(Reason.RESOLUTION_REQUIRED);
        assertThat(http.requests).isEmpty();
    }

    @Test
    void removingDependencyDefersToResolution() {
        String pyproject = resource("e-groups/pyproject.toml")
                .replace("\niniconfig = \"2.0.0\"", "");
        Result result = PoetryLockEngine.regenerate(pyproject, resource("e-groups/poetry.lock"), ctx);
        assertThat(result.isSuccess()).isFalse();
        assertThat(result.getFailure().getReason()).isEqualTo(Reason.RESOLUTION_REQUIRED);
    }

    @ParameterizedTest
    @CsvSource({
      "'# This file is automatically @generated by Poetry 1.8.3 and should not be changed by hand.\n\n', 2.0",
      "'', 1.1"
    })
    void lockWrittenBeforePoetry2IsNamedByItsLockVersion(String header, String lockVersion) {
        // packages carry no groups before lock-version 2.1, which must not read as a malformed package
        String lock = header.replace("\\n", "\n") + """
          [[package]]
          name = "six"
          version = "1.16.0"
          description = "Python 2 and 3 compatibility utilities"
          optional = false
          python-versions = ">=2.7, !=3.0.*, !=3.1.*, !=3.2.*"
          files = []

          [metadata]
          lock-version = "%s"
          python-versions = "^3.10"
          content-hash = "0000"
          """.formatted(lockVersion);
        Result result = PoetryLockEngine.regenerate(resource("e-groups/pyproject.toml"), lock, ctx);
        assertThat(result.isSuccess()).isFalse();
        assertThat(result.getFailure().getReason()).isEqualTo(Reason.MALFORMED_LOCK);
        assertThat(result.getFailure().getDetail())
          .contains("Unsupported poetry.lock lock-version: " + lockVersion + "; the native engine reads only lock-version 2.1");
    }

    @Test
    void movingADeclarationBetweenGroupsDefersToResolution() {
        // six leaves main for dev, so poetry records it under groups = ["dev"]; the version alone is unchanged
        String original = resource("e-groups/pyproject.toml");
        String edited = original.replace("six = \"1.16.0\"\n", "")
                .replace("iniconfig = \"2.0.0\"", "iniconfig = \"2.0.0\"\nsix = \"1.16.0\"");
        Result result = PoetryLockEngine.regenerate(edited, original, resource("e-groups/poetry.lock"), ctx);
        assertThat(result.isSuccess()).isFalse();
        assertThat(result.getFailure().getReason()).isEqualTo(Reason.RESOLUTION_REQUIRED);
        assertThat(result.getFailure().getPackageName()).isEqualTo("six");
        assertThat(result.getFailure().getDetail()).contains("from [main] to [dev]");
        assertThat(http.requests).isEmpty();
    }

    @Test
    void changingADeclarationsMarkerDefersToResolution() {
        String original = resource("e-groups/pyproject.toml");
        String edited = original.replace("six = \"1.16.0\"",
                "six = { version = \"1.16.0\", markers = \"python_version < '3.12'\" }");
        Result result = PoetryLockEngine.regenerate(edited, original, resource("e-groups/poetry.lock"), ctx);
        assertThat(result.isSuccess()).isFalse();
        assertThat(result.getFailure().getReason()).isEqualTo(Reason.RESOLUTION_REQUIRED);
        assertThat(result.getFailure().getDetail()).contains("more than the version of six");
        assertThat(http.requests).isEmpty();
    }

    @Test
    void lockOutOfDateBeforeTheEditIsRefused() {
        stubPypiSix();
        // attrs is declared but absent from the lock, whose hash records the manifest without it. poetry relocks that
        // drift too, and refreshing the hash over it would make the stale lock pass `poetry check --lock`.
        String original = resource("i-upgrade/pyproject.toml.before")
                .replace("six = \"1.16.0\"", "six = \"1.16.0\"\nattrs = \"25.1.0\"");
        String edited = resource("i-upgrade/pyproject.toml.after")
                .replace("six = \"1.17.0\"", "six = \"1.17.0\"\nattrs = \"25.1.0\"");
        Result result = PoetryLockEngine.regenerate(edited, original, resource("i-upgrade/poetry.lock.before"), ctx);
        assertThat(result.isSuccess()).isFalse();
        assertThat(result.getFailure().getReason()).isEqualTo(Reason.RESOLUTION_REQUIRED);
        assertThat(result.getFailure().getDetail()).contains("out of date");
        assertThat(http.requests).isEmpty();
    }

    @Test
    void newlyAddedDependencyStillDefersUnderScoping() {
        // With the original supplied, adding attrs IS the change, so it still defers to resolution.
        String original = resource("a-minimal/pyproject.toml");
        String edited = original.replace("six = \"1.16.0\"", "six = \"1.16.0\"\nattrs = \"25.1.0\"");
        Result result = PoetryLockEngine.regenerate(edited, original, resource("a-minimal/poetry.lock"), ctx);
        assertThat(result.isSuccess()).isFalse();
        assertThat(result.getFailure().getReason()).isEqualTo(Reason.RESOLUTION_REQUIRED);
        assertThat(result.getFailure().getPackageName()).isEqualTo("attrs");
    }

    static final class RoutedHttp implements HttpSender {
        final Map<String, byte[]> routes = new LinkedHashMap<>();
        final List<String> requests = new ArrayList<>();

        void route(String url, String body) {
            routes.put(url, body.getBytes(StandardCharsets.UTF_8));
        }

        @Override
        public Response send(Request request) {
            String url = request.getUrl().toString();
            requests.add(url);
            byte[] body = routes.get(url);
            if (body == null) {
                return new Response(404, new ByteArrayInputStream(new byte[0]), () -> {
                });
            }
            return new Response(200, new ByteArrayInputStream(body), () -> {
            });
        }
    }
}
