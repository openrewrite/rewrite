package org.openrewrite.csharp.search;

import lombok.EqualsAndHashCode;
import lombok.Value;
import org.jspecify.annotations.Nullable;
import org.openrewrite.ExecutionContext;
import org.openrewrite.Recipe;
import org.openrewrite.Tree;
import org.openrewrite.TreeVisitor;
import org.openrewrite.csharp.marker.GeneratedCodeOption;
import org.openrewrite.csharp.tree.Cs;
import org.openrewrite.java.tree.*;
import org.openrewrite.marker.SearchResult;

import java.util.*;

import static java.util.Arrays.asList;
import static java.util.Collections.emptyList;

/**
 * Finds generated C# files as Roslyn analyzers recognize them.
 * Intended as a negated precondition for recipes that should leave generated code alone.
 */
@EqualsAndHashCode(callSuper = false)
@Value
public class FindGeneratedCode extends Recipe {
    private static final List<String> NAME_SUFFIXES = asList(".designer", ".generated", ".g", ".g.i");

    private static final Set<String> PROXY_FOLDERS = new HashSet<>(asList(
            "service references", "web references", "connected services", "app_webreferences"));

    private static final Set<String> ATTRIBUTES = new HashSet<>(asList(
            "System.CodeDom.Compiler.GeneratedCode", "System.Runtime.CompilerServices.CompilerGenerated"));

    String displayName = "Find generated C# code";

    String description = "Find C# files that are generated, as Roslyn analyzers recognize them: by the `generated_code` option " +
                         "in `.editorconfig`, the file's name (such as `*.designer.cs`, `*.generated.cs`, `*.g.cs` or a service " +
                         "reference's `Reference.cs`), an `<auto-generated>` comment at the start of the file, or types that all " +
                         "carry a `[GeneratedCode]` or `[CompilerGenerated]` attribute.";

    @Override
    public TreeVisitor<?, ExecutionContext> getVisitor() {
        return new TreeVisitor<Tree, ExecutionContext>() {
            @Override
            public @Nullable Tree preVisit(Tree tree, ExecutionContext ctx) {
                stopAfterPreVisit();
                if (tree instanceof Cs.CompilationUnit && isGenerated((Cs.CompilationUnit) tree)) {
                    return SearchResult.found(tree);
                }
                return tree;
            }
        };
    }

    private static boolean isGenerated(Cs.CompilationUnit cu) {
        return cu.getMarkers().findFirst(GeneratedCodeOption.class)
                       .map(GeneratedCodeOption::isGenerated)
                       .orElseGet(() -> hasGeneratedName(cu) || beginsWithGeneratedHeader(cu)) ||
               declaresOnlyGeneratedTypes(cu);
    }

    private static boolean hasGeneratedName(Cs.CompilationUnit cu) {
        String[] segments = cu.getSourcePath().toString().toLowerCase(Locale.ROOT).split("[/\\\\]");
        String fileName = segments[segments.length - 1];
        int extension = fileName.lastIndexOf('.');
        String name = extension < 0 ? fileName : fileName.substring(0, extension);
        return name.startsWith("temporarygeneratedfile_") ||
               NAME_SUFFIXES.stream().anyMatch(name::endsWith) ||
               "reference".equals(name) &&
               Arrays.stream(segments, 0, segments.length - 1).anyMatch(PROXY_FOLDERS::contains);
    }

    private static boolean beginsWithGeneratedHeader(Cs.CompilationUnit cu) {
        List<Space> leading = new ArrayList<>();
        addLeadingSpaces(cu, leading);
        for (Space space : leading) {
            for (Comment comment : space.getComments()) {
                if (comment instanceof TextComment) {
                    String text = ((TextComment) comment).getText().toLowerCase(Locale.ROOT);
                    if (text.contains("<auto-generated") || text.contains("<autogenerated")) {
                        return true;
                    }
                }
            }
        }
        return false;
    }

    private static void addLeadingSpaces(Cs.CompilationUnit cu, List<Space> leading) {
        leading.add(cu.getPrefix());
        List<J> elements = new ArrayList<>(cu.getExterns());
        elements.addAll(cu.getUsings());
        elements.addAll(cu.getAttributeLists());
        elements.addAll(cu.getMembers());
        for (J element : elements) {
            leading.add(element.getPrefix());
            if (element instanceof Cs.ConditionalDirective) {
                List<Cs.CompilationUnit> branches = ((Cs.ConditionalDirective) element).getBranches();
                if (!branches.isEmpty()) {
                    addLeadingSpaces(branches.get(0), leading);
                }
            }
            if (!isDirective(element)) {
                return;
            }
        }
        leading.add(cu.getEof());
    }

    private static boolean isDirective(J element) {
        return element instanceof Cs.PragmaWarningDirective ||
               element instanceof Cs.PragmaChecksumDirective ||
               element instanceof Cs.NullableDirective ||
               element instanceof Cs.RegionDirective ||
               element instanceof Cs.EndRegionDirective ||
               element instanceof Cs.DefineDirective ||
               element instanceof Cs.UndefDirective ||
               element instanceof Cs.ErrorDirective ||
               element instanceof Cs.WarningDirective ||
               element instanceof Cs.LineDirective;
    }

    private static boolean declaresOnlyGeneratedTypes(Cs.CompilationUnit cu) {
        List<Statement> declarations = new ArrayList<>();
        addDeclarations(cu.getMembers(), declarations);
        return !declarations.isEmpty() && declarations.stream().allMatch(FindGeneratedCode::isGeneratedType);
    }

    private static void addDeclarations(List<Statement> members, List<Statement> declarations) {
        for (Statement member : members) {
            if (member instanceof Cs.NamespaceDeclaration) {
                addDeclarations(((Cs.NamespaceDeclaration) member).getMembers(), declarations);
            } else if (member instanceof Cs.ConditionalDirective) {
                for (Cs.CompilationUnit branch : ((Cs.ConditionalDirective) member).getBranches()) {
                    addDeclarations(branch.getMembers(), declarations);
                }
            } else if (!isDirective(member)) {
                declarations.add(member);
            }
        }
    }

    private static boolean isGeneratedType(Statement declaration) {
        List<Cs.AttributeList> attributeLists = new ArrayList<>();
        while (declaration instanceof Cs.AnnotatedStatement) {
            attributeLists.addAll(((Cs.AnnotatedStatement) declaration).getAttributeLists());
            declaration = ((Cs.AnnotatedStatement) declaration).getStatement();
        }
        if (declaration instanceof Cs.EnumDeclaration) {
            List<Cs.AttributeList> lists = ((Cs.EnumDeclaration) declaration).getAttributeLists();
            attributeLists.addAll(lists == null ? emptyList() : lists);
        } else if (declaration instanceof Cs.DelegateDeclaration) {
            attributeLists.addAll(((Cs.DelegateDeclaration) declaration).getAttributes());
        } else if (!(declaration instanceof J.ClassDeclaration)) {
            return false;
        }
        return attributeLists.stream()
                .flatMap(list -> list.getAttributes().stream())
                .anyMatch(FindGeneratedCode::isGeneratedCodeAttribute);
    }

    private static boolean isGeneratedCodeAttribute(J.Annotation attribute) {
        JavaType.FullyQualified type = TypeUtils.asFullyQualified(attribute.getType());
        if (type != null && !(type instanceof JavaType.Unknown)) {
            return ATTRIBUTES.contains(withoutAttributeSuffix(type.getFullyQualifiedName()));
        }
        NameTree name = attribute.getAnnotationType();
        String simpleName = name instanceof J.Identifier ? ((J.Identifier) name).getSimpleName() :
                name instanceof J.FieldAccess ? ((J.FieldAccess) name).getSimpleName() : null;
        return simpleName != null &&
               ATTRIBUTES.stream().anyMatch(a -> a.endsWith("." + withoutAttributeSuffix(simpleName)));
    }

    private static String withoutAttributeSuffix(String name) {
        return name.endsWith("Attribute") ? name.substring(0, name.length() - "Attribute".length()) : name;
    }
}
