package org.openrewrite.csharp.search;

import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.Timeout;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.CsvSource;
import org.junit.jupiter.params.provider.ValueSource;
import org.openrewrite.DocumentExample;
import org.openrewrite.InMemoryExecutionContext;
import org.openrewrite.Parser;
import org.openrewrite.SourceFile;
import org.openrewrite.Tree;
import org.openrewrite.csharp.CSharpParser;
import org.openrewrite.csharp.CSharpServer;
import org.openrewrite.csharp.marker.GeneratedCodeOption;
import org.openrewrite.csharp.rpc.CSharpRewriteRpc;
import org.openrewrite.marker.SearchResult;
import org.openrewrite.test.RecipeSpec;
import org.openrewrite.test.RewriteTest;

import java.nio.file.Path;
import java.util.List;
import java.util.concurrent.TimeUnit;

import static org.assertj.core.api.Assertions.assertThat;
import static org.openrewrite.csharp.Assertions.csharp;

@Timeout(value = 120, unit = TimeUnit.SECONDS)
class FindGeneratedCodeTest implements RewriteTest {

    @BeforeAll
    static void setUpFactory() {
        CSharpRewriteRpc.setFactory(CSharpRewriteRpc.builder().csharpServerEntry(CSharpServer.entry()));
    }

    @AfterEach
    void tearDown() {
        CSharpRewriteRpc.resetCurrent();
    }

    @AfterAll
    static void shutDown() {
        CSharpRewriteRpc.shutdownCurrent();
    }

    @Override
    public void defaults(RecipeSpec spec) {
        spec.recipe(new FindGeneratedCode());
    }

    @DocumentExample
    @Test
    void header() {
        rewriteRun(
          csharp(
            "// <auto-generated />\nclass C { }",
            "// <auto-generated />\n/*~~>*/class C { }"
          )
        );
    }

    @ParameterizedTest
    @CsvSource({
      "Form1.Designer.cs, true",
      "Model.generated.cs, true",
      "App.g.cs, true",
      "App.g.i.cs, true",
      "TemporaryGeneratedFile_1.cs, true",
      "Service References/Orders/Reference.cs, true",
      "App\\Web References\\Orders\\Reference.cs, true",
      "Designer.cs, false",
      "Domain/Reference.cs, false",
      "Migrations/20260515_Init.cs, false"
    })
    void name(String path, boolean generated) {
        assertThat(isFound(parse("class C { }").withSourcePath(Path.of(path)))).isEqualTo(generated);
    }

    @ParameterizedTest
    @ValueSource(strings = {
      "// <autogenerated>\n// </autogenerated>\nusing System;\nclass C { }",
      "//----\n// <auto-generated>\n//     By a tool.\n// </auto-generated>\n//----\nnamespace N { class C { } }",
      "/* <auto-generated/> */\n[assembly: System.CLSCompliant(true)]",
      "#pragma warning disable 1591\n// <auto-generated />\nusing System;\nclass C { }",
      "#region Designer generated code\n#nullable disable\n// <auto-generated />\nclass C { }\n#endregion",
      "#if DEBUG\n// <auto-generated />\nclass C { }\n#else\nclass D { }\n#endif",
      "// <auto-generated />",
      "namespace N { [System.CodeDom.Compiler.GeneratedCode(\"t\", \"1\")] class C { } [System.CodeDom.Compiler.GeneratedCodeAttribute(\"t\", \"1\")] enum E { A } }",
      "[System.CodeDom.Compiler.GeneratedCode(\"t\", \"1\")] delegate void D();",
      "#if DEBUG\n[System.Runtime.CompilerServices.CompilerGenerated] class C { }\n#endif"
    })
    void generated(String source) {
        assertThat(isFound(parse(source))).isTrue();
    }

    @ParameterizedTest
    @ValueSource(strings = {
      "class C { }\n// <auto-generated />\nclass D { }",
      "// generated by hand\nclass C { }",
      "class C { string s = \"<auto-generated />\"; }",
      "",
      "[System.CodeDom.Compiler.GeneratedCode(\"t\", \"1\")] class C { } class D { }",
      "[System.Obsolete] class C { }"
    })
    void handWritten(String source) {
        assertThat(isFound(parse(source))).isFalse();
    }

    @ParameterizedTest
    @CsvSource({"C.cs, true", "C.designer.cs, false"})
    void optionWinsOverName(String path, boolean option) {
        SourceFile cu = parse("class C { }").withSourcePath(Path.of(path));

        assertThat(isFound(cu.withMarkers(cu.getMarkers().add(new GeneratedCodeOption(Tree.randomId(), option))))).isEqualTo(option);
    }

    private static SourceFile parse(String source) {
        return CSharpParser.builder().build()
          .parseInputs(List.of(Parser.Input.fromString(Path.of("source.cs"), source)), null, new InMemoryExecutionContext())
          .findFirst()
          .orElseThrow();
    }

    private static boolean isFound(SourceFile cu) {
        Tree after = new FindGeneratedCode().getVisitor().visitNonNull(cu, new InMemoryExecutionContext());
        return after.getMarkers().findFirst(SearchResult.class).isPresent();
    }
}
