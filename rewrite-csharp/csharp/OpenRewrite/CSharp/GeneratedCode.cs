using OpenRewrite.Core;
using OpenRewrite.Java;

namespace OpenRewrite.CSharp;

/// <summary>
/// Recognizes generated code as Roslyn analyzers do: by the <c>generated_code</c> option, the file's name, the
/// comment it begins with, or a <c>[GeneratedCode]</c> or <c>[CompilerGenerated]</c> attribute.
/// </summary>
public static class GeneratedCode
{
    private static readonly string[] NameSuffixes = [".designer", ".generated", ".g", ".g.i"];

    private static readonly string[] ProxyFolders =
        ["Service References", "Web References", "Connected Services", "App_WebReferences"];

    private static readonly string[] HeaderTags = ["<auto-generated", "<autogenerated"];

    private static readonly AttributeMatcher[] Attributes =
    [
        new("System.CodeDom.Compiler.GeneratedCodeAttribute"),
        new("System.Runtime.CompilerServices.CompilerGeneratedAttribute")
    ];

    /// <summary>
    /// Whether the whole file is generated. The <c>generated_code</c> option wins over the file's name and header,
    /// as it does in Roslyn; a file that declares nothing but generated types is generated whatever the option says.
    /// </summary>
    public static bool IsGenerated(CompilationUnit cu) =>
        (cu.Markers.FindFirst<GeneratedCodeOption>()?.Generated ??
         (HasGeneratedName(cu.SourcePath) || BeginsWithGeneratedHeader(cu))) ||
        DeclaresOnlyGeneratedTypes(cu);

    /// <summary>
    /// Whether the declaration carries a <c>[GeneratedCode]</c> or <c>[CompilerGenerated]</c> attribute.
    /// </summary>
    public static bool IsGenerated(Statement declaration) => AttributeListsOf(declaration)
        .SelectMany(list => list.Attributes)
        .Any(attribute => Attributes.Any(matcher => matcher.Matches(attribute.Element)));

    /// <summary>
    /// Keeps <paramref name="visitor"/> from changing generated code, unless the recipe visits it.
    /// </summary>
    internal static ITreeVisitor<Core.ExecutionContext> Guard(Recipe recipe, ITreeVisitor<Core.ExecutionContext> visitor) =>
        recipe.VisitsGeneratedCode || visitor is NoopVisitor<Core.ExecutionContext>
            ? visitor
            : new GeneratedCodeGuard(visitor);

    internal static bool IsType(Statement declaration) => declaration switch
    {
        AnnotatedStatement annotated => IsType(annotated.Statement),
        ClassDeclaration or EnumDeclaration or DelegateDeclaration => true,
        _ => false
    };

    private static IEnumerable<AttributeList> AttributeListsOf(Statement declaration) => declaration switch
    {
        AnnotatedStatement annotated => annotated.AttributeLists.Concat(AttributeListsOf(annotated.Statement)),
        EnumDeclaration { AttributeLists: { } lists } => lists,
        DelegateDeclaration @delegate => @delegate.Attributes,
        PropertyDeclaration property => property.AttributeLists,
        EventDeclaration @event => @event.AttributeLists,
        OperatorDeclaration @operator => @operator.AttributeLists,
        AccessorDeclaration accessor => accessor.AttributeLists,
        _ => []
    };

    private static bool HasGeneratedName(string sourcePath)
    {
        var segments = sourcePath.Split('/', '\\');
        var name = Path.GetFileNameWithoutExtension(segments[^1]);
        return name.StartsWith("TemporaryGeneratedFile_", StringComparison.OrdinalIgnoreCase) ||
               NameSuffixes.Any(suffix => name.EndsWith(suffix, StringComparison.OrdinalIgnoreCase)) ||
               name.Equals("Reference", StringComparison.OrdinalIgnoreCase) &&
               segments.SkipLast(1).Any(folder => ProxyFolders.Contains(folder, StringComparer.OrdinalIgnoreCase));
    }

    private static bool BeginsWithGeneratedHeader(CompilationUnit cu) => LeadingSpaces(cu)
        .SelectMany(space => space.Comments)
        .OfType<TextComment>()
        .Any(comment => HeaderTags.Any(tag => comment.Text.Contains(tag, StringComparison.OrdinalIgnoreCase)));

    private static IEnumerable<Space> LeadingSpaces(CompilationUnit cu)
    {
        yield return cu.Prefix;
        foreach (var element in cu.Externs.Concat(cu.Usings).Select(s => (J)s.Element)
                     .Concat(cu.AttributeLists)
                     .Concat(cu.Members.Select(s => (J)s.Element)))
        {
            yield return element.Prefix;
            if (element is ConditionalDirective { Branches: [var branch, ..] })
            {
                foreach (var space in LeadingSpaces(branch.Element))
                    yield return space;
            }
            if (!IsDirective(element))
                yield break;
        }
        yield return cu.Eof;
    }

    private static bool IsDirective(J element) => element is PragmaWarningDirective or PragmaChecksumDirective
        or NullableDirective or RegionDirective or EndRegionDirective or DefineDirective or UndefDirective
        or ErrorDirective or WarningDirective or LineDirective;

    private static bool DeclaresOnlyGeneratedTypes(CompilationUnit cu)
    {
        var any = false;
        foreach (var declaration in Declarations(cu.Members))
        {
            if (!IsType(declaration) || !IsGenerated(declaration))
                return false;
            any = true;
        }
        return any;
    }

    private static IEnumerable<Statement> Declarations(IEnumerable<JRightPadded<Statement>> members) => members
        .Select(member => member.Element)
        .Where(member => !IsDirective(member))
        .SelectMany(member => member switch
        {
            NamespaceDeclaration ns => Declarations(ns.Members),
            ConditionalDirective conditional => conditional.Branches.SelectMany(b => Declarations(b.Element.Members)),
            _ => [member]
        });
}
