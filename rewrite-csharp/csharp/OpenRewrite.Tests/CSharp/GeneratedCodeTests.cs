using OpenRewrite.Core;
using OpenRewrite.CSharp;
using OpenRewrite.CSharp.Rpc;
using OpenRewrite.Java;
using OpenRewrite.Test;
using static OpenRewrite.Java.J;
using ExecutionContext = OpenRewrite.Core.ExecutionContext;

namespace OpenRewrite.Tests.CSharp;

public class GeneratedCodeTests : RewriteTest
{
    [Theory]
    [InlineData("Form1.Designer.cs")]
    [InlineData("Model.generated.cs")]
    [InlineData("App.g.cs")]
    [InlineData("App.g.i.cs")]
    [InlineData("TemporaryGeneratedFile_1.cs")]
    [InlineData("Service References/Orders/Reference.cs")]
    [InlineData("App\\Web References\\Orders\\Reference.cs")]
    public void ByName(string path) =>
        Assert.True(GeneratedCode.IsGenerated(Parse("class C { }", path)));

    [Theory]
    [InlineData("Designer.cs")]
    [InlineData("Domain/Reference.cs")]
    [InlineData("Migrations/20260515_Init.cs")]
    public void NotByName(string path) =>
        Assert.False(GeneratedCode.IsGenerated(Parse("class C { }", path)));

    [Theory]
    [InlineData("// <auto-generated />\nclass C { }")]
    [InlineData("// <autogenerated>\n// </autogenerated>\nusing System;\nclass C { }")]
    [InlineData("//----\n// <auto-generated>\n//     By a tool.\n// </auto-generated>\n//----\nnamespace N { class C { } }")]
    [InlineData("/* <auto-generated/> */\n[assembly: System.CLSCompliant(true)]")]
    [InlineData("#pragma warning disable 1591\n// <auto-generated />\nusing System;\nclass C { }")]
    [InlineData("#region Designer generated code\n#nullable disable\n// <auto-generated />\nclass C { }\n#endregion")]
    [InlineData("#if DEBUG\n// <auto-generated />\nclass C { }\n#else\nclass D { }\n#endif")]
    [InlineData("// <auto-generated />")]
    public void ByHeader(string source) =>
        Assert.True(GeneratedCode.IsGenerated(Parse(source)));

    [Theory]
    [InlineData("class C { }\n// <auto-generated />\nclass D { }")]
    [InlineData("// generated by hand\nclass C { }")]
    [InlineData("class C { string s = \"<auto-generated />\"; }")]
    [InlineData("")]
    public void NotByHeader(string source) =>
        Assert.False(GeneratedCode.IsGenerated(Parse(source)));

    [Theory]
    [InlineData("namespace N { [System.CodeDom.Compiler.GeneratedCode(\"t\", \"1\")] class C { } [System.CodeDom.Compiler.GeneratedCodeAttribute(\"t\", \"1\")] enum E { A } }", true)]
    [InlineData("[System.CodeDom.Compiler.GeneratedCode(\"t\", \"1\")] delegate void D();", true)]
    [InlineData("[System.CodeDom.Compiler.GeneratedCode(\"t\", \"1\")] class C { } class D { }", false)]
    public void ByDeclaringOnlyGeneratedTypes(string source, bool expected) =>
        Assert.Equal(expected, GeneratedCode.IsGenerated(Parse(source)));

    [Theory]
    [InlineData("class C { }", "C.cs", true)]
    [InlineData("// <auto-generated />\nclass C { }", "C.designer.cs", false)]
    public void OptionWinsOverNameAndHeader(string source, string path, bool option)
    {
        var cu = Parse(source, path);

        Assert.Equal(option, GeneratedCode.IsGenerated(
            cu.WithMarkers(cu.Markers.Add(new GeneratedCodeOption(Guid.NewGuid(), option)))));
    }

    [Fact]
    public void RecipesVisitGeneratedCodeByDefault() => RewriteRun(
        spec => spec.SetRecipe(new UpperCaseNames()),
        CSharp("// <auto-generated />\nclass c { }", "// <auto-generated />\nclass C { }"));

    [Fact]
    public void GeneratedFileIsLeftAlone() => RewriteRun(
        spec => spec.SetRecipe(new UpperCaseNames { Visits = false }),
        CSharp("// <auto-generated />\nclass c { }"),
        CSharp("class d { }", "class D { }"));

    [Fact]
    public void FileOfAnEditorConfigSectionForGeneratedCodeIsLeftAlone() => RewriteRun(
        spec => spec.SetRecipe(new UpperCaseNames { Visits = false }),
        EditorConfig("[Proxies/**.cs]\ngenerated_code = true\n"),
        CSharp("class c { }", sourcePath: "Proxies/C.cs"),
        CSharp("class d { }", "class D { }", "D.cs"));

    [Fact]
    public void FileThatIsOnlyPartlyGeneratedIsVisited() => RewriteRun(
        spec => spec.SetRecipe(new UpperCaseNames { Visits = false }),
        CSharp(
            """
            class a { }
            [System.CodeDom.Compiler.GeneratedCode("tool", "1.0")]
            class b { }
            """,
            """
            class A { }
            [System.CodeDom.Compiler.GeneratedCode("tool", "1.0")]
            class B { }
            """));

    [Theory]
    [InlineData("C.g.cs", false)]
    [InlineData("C.cs", true)]
    public void FileMarkedByAnEarlierSearch(string path, bool edited)
    {
        var cu = SearchResult.Found(Parse("class c { }", path));
        var recipe = new UpperCaseNames { Visits = false };

        var after = GeneratedCode.Gate(recipe, recipe.GetVisitor()).Visit(cu, new ExecutionContext());

        Assert.Equal(edited, !ReferenceEquals(cu, after));
    }

    [Fact]
    public void PreconditionOfARecipeThatVisitsGeneratedCode() => RewriteRun(
        spec => spec.SetRecipe(new FindClasses()),
        CSharp("class c { }", sourcePath: "C.g.cs"),
        CSharp("class d { }", "class /*~~>*/d { }", "D.cs"));

    [Fact]
    public async Task HostEvaluatesThePreconditionARecipeDeclares()
    {
        var (_, prepared) = await Prepare(new FindClasses());

        Assert.Equivalent(new Precondition
        {
            Op = "not",
            Operands = [new Precondition { VisitorName = "org.openrewrite.csharp.search.FindGeneratedCode", VisitorOptions = [] }]
        }, prepared.EditPreconditions[0], strict: true);
    }

    [Fact]
    public async Task HostDoesNotEvaluateThePreconditionOfARecipeThatSkipsGeneratedCode()
    {
        var (server, prepared) = await Prepare(new UpperCaseNames { Visits = false });
        var ctx = new ExecutionContext();
        var cu = Parse("class c { }", "C.g.cs");

        Assert.Equal("org.openrewrite.rpc.internal.FindTreesOfType", Assert.Single(prepared.EditPreconditions).VisitorName);
        Assert.Same(cu, server.VisitorFor(prepared.EditVisitor, ctx).Visit(cu, ctx, new Cursor()));
    }

    [Fact]
    public void EditorIsVisitedUnderTheGivenCursor()
    {
        var editor = new RecordParent();
        var parent = new Cursor(new Cursor(), "parent");

        GeneratedCode.Gate(new UpperCaseNames { Visits = false }, editor)
            .Visit(Parse("class c { }"), new ExecutionContext(), parent);

        Assert.Same(parent, editor.Parent);
    }

    [Fact]
    public async Task EditorsButNotScannersSkipGeneratedCodeOverRpc()
    {
        var recipe = new CountFiles();
        var (server, prepared) = await Prepare(recipe);
        var cu = Parse("// <auto-generated />\nclass C { }");
        var ctx = new ExecutionContext();

        server.VisitorFor(prepared.ScanVisitor!, ctx).Visit(cu, ctx);
        var edited = server.VisitorFor(prepared.EditVisitor, ctx).Visit(cu, ctx, new Cursor());

        Assert.Equal(1, recipe.Scanned);
        Assert.Same(cu, edited);
    }

    private static CompilationUnit Parse(string source, string path = "source.cs") =>
        new CSharpParser().Parse(source, path);

    private static async Task<(RewriteRpcServer, PrepareRecipeResponse)> Prepare(global::OpenRewrite.Core.Recipe recipe)
    {
        var marketplace = new RecipeMarketplace();
        marketplace.Install(recipe, new CategoryDescriptor("Test"));
        var server = new RewriteRpcServer(marketplace);
        return (server, await server.PrepareRecipe(new PrepareRecipeRequest { Id = recipe.Name }));
    }

    private sealed class UpperCaseNames : global::OpenRewrite.Core.Recipe
    {
        public bool Visits { get; init; } = true;
        public override string DisplayName => "Upper case names";
        public override string Description => "Upper cases the names of types and methods.";
        public override bool VisitsGeneratedCode => Visits && base.VisitsGeneratedCode;
        public override ITreeVisitor<ExecutionContext> GetVisitor() => new Visitor();

        private sealed class Visitor : CSharpVisitor<ExecutionContext>
        {
            public override J VisitClassDeclaration(ClassDeclaration cd, ExecutionContext ctx)
            {
                cd = (ClassDeclaration)base.VisitClassDeclaration(cd, ctx);
                return cd.WithName(cd.Name.WithSimpleName(cd.Name.SimpleName.ToUpperInvariant()));
            }
        }
    }

    private sealed class RecordParent : CSharpVisitor<ExecutionContext>
    {
        public Cursor? Parent { get; private set; }

        public override J VisitCompilationUnit(CompilationUnit cu, ExecutionContext ctx)
        {
            Parent = Cursor.Parent;
            return cu;
        }
    }

    private sealed class FindClasses : global::OpenRewrite.Core.Recipe
    {
        public override string DisplayName => "Find classes";
        public override string Description => "Finds classes outside of generated code.";
        public override ITreeVisitor<ExecutionContext> GetVisitor() => Preconditions.Check(
            Preconditions.Not(global::OpenRewrite.Java.Search.Preconditions.IsGeneratedCode()), new Visitor());

        private sealed class Visitor : CSharpVisitor<ExecutionContext>
        {
            public override J VisitClassDeclaration(ClassDeclaration cd, ExecutionContext ctx) =>
                cd.WithName(SearchResult.Found(cd.Name));
        }
    }

    private sealed class CountFiles : ScanningRecipe<List<string>>
    {
        private readonly List<string> _scanned = [];
        public int Scanned => _scanned.Count;
        public override string DisplayName => "Count files";
        public override string Description => "Counts files and marks them.";
        public override bool VisitsGeneratedCode => false;
        public override List<string> GetInitialValue(ExecutionContext ctx) => _scanned;
        public override ITreeVisitor<ExecutionContext> GetScanner(List<string> acc) => new Scanner(acc);
        public override ITreeVisitor<ExecutionContext> GetVisitor(List<string> acc) => new Editor();

        private sealed class Scanner(List<string> acc) : CSharpVisitor<ExecutionContext>
        {
            public override J VisitCompilationUnit(CompilationUnit cu, ExecutionContext ctx)
            {
                acc.Add(cu.SourcePath);
                return cu;
            }
        }

        private sealed class Editor : CSharpVisitor<ExecutionContext>
        {
            public override J VisitCompilationUnit(CompilationUnit cu, ExecutionContext ctx) => SearchResult.Found(cu);
        }
    }
}
